"""
Writes the evaluation weights in ChessGame/EvalParams.py to engine/src/params.rs, so the Rust
engine uses the same (Texel-tuned) weights as the Python one. Run after every tuning run:

    python tuning/export_rust_params.py
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from ChessGame.EvalParams import mgValue, egValue, mgTable, egTable, termNames, termMg, termEg

OUT = os.path.join(os.path.dirname(__file__), "..", "engine", "src", "params.rs")
PIECES = "PNBRQK"


def table(name, values):
    rows = [", ".join(f"{v:5}" for v in values[r * 8:(r + 1) * 8]) for r in range(8)]
    body = "\n".join(f"        {row}," for row in rows)
    return f"    // {name}\n    [\n{body}\n    ],"


def main():
    out = [
        "//! Evaluation weights in centipawns. GENERATED by tuning/export_rust_params.py from",
        "//! ChessGame/EvalParams.py: edit the Python file (or re-run the tuner) and regenerate, don't edit here.",
        "//!",
        "//! Tables are from White's point of view, rank 8 first, as in the Python file.",
        "",
        "/// Material by piece type: pawn, knight, bishop, rook, queen, king",
        f"pub const MG_VALUE: [i32; 6] = [{', '.join(str(mgValue[p]) for p in PIECES)}];",
        f"pub const EG_VALUE: [i32; 6] = [{', '.join(str(egValue[p]) for p in PIECES)}];",
        "",
        "#[rustfmt::skip]",
        "pub const MG_TABLE: [[i32; 64]; 6] = [",
        *[table(p, mgTable[p]) for p in PIECES],
        "];",
        "",
        "#[rustfmt::skip]",
        "pub const EG_TABLE: [[i32; 64]; 6] = [",
        *[table(p, egTable[p]) for p in PIECES],
        "];",
        "",
        f"/// Positional terms, in this order: {', '.join(termNames)}",
        f"pub const TERM_MG: [i32; {len(termNames)}] = [{', '.join(str(termMg[n]) for n in termNames)}];",
        f"pub const TERM_EG: [i32; {len(termNames)}] = [{', '.join(str(termEg[n]) for n in termNames)}];",
        "",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
