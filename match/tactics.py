"""
Tactical regression suite: do the selective search techniques hide tactics?

    python match/tactics.py generate tuning/data/quiet-labeled.v7.epd.gz [--scan 20000]   # writes match/tactics.epd
    python match/tactics.py solve [--time 1.0]                                             # solve rate per configuration

generate: searches positions full-width (no pruning, reductions or extensions, so a depth-d result is
exact for depth d plus quiescence) and keeps those with a decisive, unique best move:
  - the search finds a forced mate, or gains at least GAIN centipawns over the static evaluation
  - every other move is at least MARGIN centipawns worse
Each line is "FEN bm <uci move>; c0 <score>;".

solve: gives every position the same thinking time under each configuration and counts how often the
engine plays the solution: the full-width-at-root baseline, each technique alone on top of it,
all of them, and all but one. A technique that hides tactics lowers the count where it's switched on.
Run it with PyPy for realistic depths.
"""

import argparse
import gzip
import os
import random
import sys
from multiprocessing import Pool

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from ChessGame.ChessEngine import GameState
from ChessGame.ChessAI import Searcher, evaluate, FEATURES, MATE_BOUND

SUITE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tactics.epd")
DEPTH = 4
GAIN = 300
MARGIN = 200


def uci(move):
    return move.getChessNotation() + move.promotionSuffix()


def fullWidth(gs, moves):
    searcher = Searcher(timeLimit = float("inf"), maxDepth = DEPTH, usePruning = False)
    move = searcher.search(gs, moves)
    return move, searcher.bestScore


# One candidate position -> (fen, solution, score) if it's a clear tactic, else None
def classify(fen):
    gs = GameState.fromFen(fen)
    moves = gs.getValidateMoves()
    if len(moves) < 2:
        return None
    static = evaluate(gs)
    best, score = fullWidth(gs, moves)
    if score < MATE_BOUND and score - static < GAIN:
        return None
    others = [m for m in moves if m.moveID != best.moveID]
    _, second = fullWidth(gs, others)
    if score - second < MARGIN:
        return None
    return fen, uci(best), score


def readFens(path, scan, seed = 7):
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt") as f:
        lines = f.readlines()
    random.Random(seed).shuffle(lines)
    return [" ".join(line.split()[:4]) + " 0 1" for line in lines[:scan]]


def generate(args):
    fens = readFens(args.dataset, args.scan)
    found = []
    with Pool(args.processes) as pool:
        for n, result in enumerate(pool.imap_unordered(classify, fens, chunksize = 8)):
            if result is not None:
                found.append(result)
            if (n + 1) % 500 == 0:
                print(f"  {n + 1}/{len(fens)} scanned, {len(found)} tactics", flush = True)
    found.sort()
    with open(SUITE, "w") as f:
        f.write(f"# Generated by match/tactics.py: full-width depth {DEPTH}, gain >= {GAIN} or mate, unique by {MARGIN}\n")
        for fen, move, score in found:
            f.write(f"{fen} bm {move}; c0 {score};\n")
    print(f"Wrote {len(found)} positions to {SUITE}")


def configurations():
    configs = [("baseline (PVS only)", set(FEATURES))]
    configs += [(f"+{name} only", set(FEATURES) - {name}) for name in FEATURES]
    configs.append(("all on", set()))
    configs += [(f"all but {name}", {name}) for name in FEATURES]
    return configs


def solveOne(job):
    fen, solution, disabled, timeLimit = job
    searcher = Searcher(timeLimit = timeLimit, disabled = disabled)
    move = searcher.search(GameState.fromFen(fen))
    return uci(move) == solution


def warmUp(_):
    # Let PyPy's JIT compile the search before anything is timed
    Searcher(timeLimit = 3).search(GameState())


def solve(args):
    suite = []
    with open(SUITE) as f:
        for line in f:
            if line.startswith("#") or " bm " not in line:
                continue
            fen, rest = line.split(" bm ")
            suite.append((fen.strip(), rest.split(";")[0].strip()))
    print(f"{len(suite)} positions, {args.time}s each\n")
    with Pool(args.processes) as pool:
        pool.map(warmUp, range(args.processes * 2))
        for name, disabled in configurations():
            jobs = [(fen, move, tuple(disabled), args.time) for fen, move in suite]
            solved = sum(pool.map(solveOne, jobs, chunksize = 1))
            print(f"{name:26s} {solved:4d}/{len(suite)}  ({solved / len(suite):.0%})", flush = True)


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest = "command", required = True)
    gen = sub.add_parser("generate")
    gen.add_argument("dataset")
    gen.add_argument("--scan", type = int, default = 20000)
    gen.add_argument("--processes", type = int, default = max(1, (os.cpu_count() or 2) - 2))
    sol = sub.add_parser("solve")
    sol.add_argument("--time", type = float, default = 1.0)
    sol.add_argument("--processes", type = int, default = max(1, (os.cpu_count() or 2) - 2))
    args = parser.parse_args()
    generate(args) if args.command == "generate" else solve(args)


if __name__ == "__main__":
    main()
